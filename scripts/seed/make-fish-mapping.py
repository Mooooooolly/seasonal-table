def frozen(n):
    return n["crop_code"].strip().startswith("3") or bool(FROZEN_RE.search(n["crop_name"]))


rows = []
for n in names:
    raw = n["crop_name"]
    code = n["crop_code"].strip()
    base = FROZEN_RE.sub("", raw).strip()
    fz = frozen(n)
    note = ""
    if base in UNCLEAR or raw in UNCLEAR:
        group, role, conf, note = "其他海鮮", "不適用(非蔬菜或不明)", "高", "籠統名稱,不對應單一食材"
    elif code.startswith("6") or ALIAS.get(base, ("", "", ""))[2] is None:
        group, role, conf = ALIAS.get(base, (base,))[0], "不適用(加工品)", "高"
        note = "加工品(熟品、魚漿、魚卵、部位副產品等)"
    else:
        group, conf, note = ALIAS.get(base, (base, "中" if base in KNOWN else "低", "" if base in KNOWN else "自動依名稱歸類,請確認"))
        role = "主食材"
    if fz and role == "主食材":
        group = f"{group}(冷凍)"
        note = ("冷凍品,不判斷盛產。" + (note or "")).rstrip("。")
    rows.append({
        "crop_name": raw, "group_name": group, "crop_code": code, "role": role, "confidence": conf,
        "is_import": "否", "frozen": "是" if fz else "否", "note": note,
        "vol_12m_ton": n["qty_ton"], "avg_price_12m_per_kg": n["avg_price_kg"], "trade_days_12m": n["trade_days"],
    })

out = ROOT / "data/seed/fish-mapping.csv"
with out.open("w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
    w.writeheader()
    w.writerows(rows)

groups = {}
for r in rows:
    groups.setdefault((r["group_name"], r["role"]), 0)
    groups[(r["group_name"], r["role"])] += 1
by_role = {}
for (g, role) in groups:
    by_role[role] = by_role.get(role, 0) + 1
conf = {}
for r in rows:
    conf[r["confidence"]] = conf.get(r["confidence"], 0) + 1
print(f"{len(rows)} 個品名 → {len(groups)} 個群組;群組角色:{by_role};信心:{conf}")
# 同一群組角色必須一致
gr = {}
for r in rows:
    gr.setdefault(r["group_name"], set()).add(r["role"])
bad = {g: s for g, s in gr.items() if len(s) > 1}
print("角色不一致的群組:", bad or "無")
